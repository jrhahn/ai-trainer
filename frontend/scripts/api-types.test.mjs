import { describe, expect, it } from 'vitest'
import { toTypeScript } from './api-types.mjs'

describe('toTypeScript (ai-trainer-ops#276)', () => {
  it('writes each schema Pydantic emits as a type', () => {
    const spec = {
      components: {
        schemas: {
          'Plan-Output': {
            type: 'object',
            required: ['days', 'kind'],
            properties: {
              days: { type: 'array', items: { anyOf: [{ $ref: '#/components/schemas/Day' }, { type: 'null' }] } },
              kind: { enum: ['week', 'block'] },
              note: { anyOf: [{ type: 'string' }, { type: 'null' }] },
              'x-tag': { const: 'plan' },
              byDate: { type: 'object', additionalProperties: { type: 'integer' } },
              extra: { type: 'object' },
              anything: {},
            },
          },
          Day: { type: 'object', properties: { date: { type: 'string' }, done: { type: 'boolean' } } },
        },
      },
    }

    expect(toTypeScript(spec).split('\n').slice(3).join('\n')).toBe(
      [
        'export type Day = {',
        '  date?: string',
        '  done?: boolean',
        '}',
        '',
        'export type Plan_Output = {',
        '  days: (Day | null)[]',
        '  kind: "week" | "block"',
        '  note?: string | null',
        '  "x-tag"?: "plan"',
        '  byDate?: Record<string, number>',
        '  extra?: Record<string, unknown>',
        '  anything?: unknown',
        '}',
        '',
      ].join('\n'),
    )
  })

  it('says where the file comes from', () => {
    expect(toTypeScript({})).toMatch(/^\/\/ Generated by `npm run types:api`/)
  })
})
