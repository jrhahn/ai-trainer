// The backend's response and request shapes as TypeScript (ai-trainer-ops#276):
// `npm run types:api` writes src/types/api.gen.ts from the backend's OpenAPI
// schema, and `npm run types:api:check` fails when the file is out of date, so a
// schema change without regenerating fails CI.
//
// ponytail: converts only what Pydantic emits ($ref, anyOf, enum, const, type,
// items, properties/required, additionalProperties). openapi-typescript does
// all of OpenAPI but wants TypeScript 5, and this repo is on 6; switch to it
// once it takes 6.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const HEADER =
  "// Generated by `npm run types:api` from the backend's OpenAPI schema (ai-trainer-ops#276).\n" +
  '// Do not edit: change the backend\'s schemas and run it again.\n'

/** A schema name as an identifier: FastAPI names some `Model-Input` / `Model-Output`. */
const typeName = (name) => name.replace(/[^A-Za-z0-9_$]/g, '_')

const propertyKey = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key))

const grouped = (type) => (type.includes(' | ') ? `(${type})` : type)

function typeOf(schema, indent) {
  if (schema.$ref) return typeName(schema.$ref.split('/').pop())
  if (schema.anyOf) return schema.anyOf.map((part) => typeOf(part, indent)).join(' | ')
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ')
  if ('const' in schema) return JSON.stringify(schema.const)
  if (Array.isArray(schema.type)) return schema.type.map((type) => typeOf({ ...schema, type }, indent)).join(' | ')
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return `${grouped(typeOf(schema.items ?? {}, indent))}[]`
    case 'object':
      return objectOf(schema, indent)
    default:
      return 'unknown'
  }
}

function objectOf(schema, indent) {
  const properties = Object.entries(schema.properties ?? {})
  const extra = schema.additionalProperties
  if (properties.length === 0) {
    return extra && extra !== true ? `Record<string, ${typeOf(extra, indent)}>` : 'Record<string, unknown>'
  }
  const required = new Set(schema.required ?? [])
  const inner = `${indent}  `
  const lines = properties.map(
    ([key, value]) => `${inner}${propertyKey(key)}${required.has(key) ? '' : '?'}: ${typeOf(value, inner)}`,
  )
  return `{\n${lines.join('\n')}\n${indent}}`
}

/** The schema's components as one exported type each, sorted by name. */
export function toTypeScript(spec) {
  const schemas = spec.components?.schemas ?? {}
  const types = Object.keys(schemas)
    .sort()
    .map((name) => `export type ${typeName(name)} = ${typeOf(schemas[name], '')}\n`)
  return `${HEADER}\n${types.join('\n')}`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL('../src/types/api.gen.ts', import.meta.url))
  // `--no-sync`: use the backend's environment as it is (CI synced it a step before).
  const spec = JSON.parse(
    execFileSync('uv', ['run', '--no-sync', 'python', 'scripts/export_openapi.py'], {
      cwd: fileURLToPath(new URL('../../backend/', import.meta.url)),
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    }),
  )
  const text = toTypeScript(spec)
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(out, 'utf8')
    } catch {
      // missing counts as out of date
    }
    if (current !== text) {
      console.error('src/types/api.gen.ts is out of date with the backend. Run `npm run types:api` and commit it.')
      process.exit(1)
    }
  } else {
    writeFileSync(out, text)
  }
}
