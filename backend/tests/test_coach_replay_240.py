"""Real coach replies, replayed through the checks every reply goes through (ai-trainer-ops#240).

**Synthetic test data.** The athletes are the fictional QA personas from the
app's test runs (Lena, Mia, Sam, Tom, Werner). The replies were generated by
the coach model in a test run against those personas (persona run 5,
2026-10-24). No real person's data is in them; tests/fixtures/README.md says
the same beside the file.

None of them reached its athlete with a note from the app. Replayed through
ask_trainer's post-processing with the context the coach saw (the sections
"Why this answer?" lists), each must still pass untouched: a change to the
checks that would put a note under a real, unremarkable reply fails here, at
no model cost.

Fifteen of the run's 22 replies are here. The other seven name numbers from
the plan as it stood when the athlete asked (today's watts, Monday's minutes),
and the run recorded the plan only after a change, so they cannot be replayed
faithfully.

The fixture is kept in Git LFS. A checkout without ``git lfs pull`` holds the
pointer file: the test skips then, except in CI, where ``REQUIRE_LFS_FIXTURES``
makes a missing file fail instead of going quiet.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from unittest.mock import patch

import pytest

from services import ai_service

FIXTURE = Path(__file__).parent / "fixtures" / "coach_replies_run5.json"
_LFS_POINTER = "version https://git-lfs.github.com/spec/v1"

_text = FIXTURE.read_text(encoding="utf-8")
if _text.startswith(_LFS_POINTER):
    if os.environ.get("REQUIRE_LFS_FIXTURES"):
        raise RuntimeError(
            f"{FIXTURE.name} is a Git LFS pointer, not the fixture: the checkout "
            "needs lfs: true"
        )
    pytest.skip(
        f"{FIXTURE.name} is a Git LFS pointer; run `git lfs pull` to replay it",
        allow_module_level=True,
    )
CASES = json.loads(_text)


def test_the_replies_are_the_runs_own():
    assert len(CASES) == 15
    assert {case["language"] for case in CASES} == {"German", "English"}
    assert sum(1 for case in CASES if case["reply"]["planUpdates"]) == 3


@pytest.mark.asyncio
@pytest.mark.parametrize("case", CASES, ids=lambda c: f"{c['persona']}-{c['turn']}")
async def test_a_real_reply_passes_the_checks_untouched(case):
    async def coach(provider, system_prompt, messages, json_mode=False, **kwargs):
        return json.dumps(case["reply"])

    with patch.object(ai_service, "_chat_history", side_effect=coach):
        result = await ai_service.ask_trainer(
            case["message"],
            case["plan"],
            {"name": case["persona"].split("-")[0].title()},
            provider="gemini",
            metrics_history_section=case["context"],
            interface_language=case["language"],
            reply_language=case["language"],
        )

    assert result["notes"] == []
    assert result["response"] == case["reply"]["response"]
